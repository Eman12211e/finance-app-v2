"""Build data/paper/scenarios/synthetic-a.json: fictional daily OHLCV bars from a fixed seed. Offline, no data source.
The same seed always produces the same file. Prices are integer cents; dates are Monday-Friday business days
(market holidays are not modelled). Tickers and companies are fictional; nothing here is real market data."""
import json
import os
import random
from datetime import date, timedelta

OUT_PATH = os.path.join(os.path.dirname(__file__), "..", "data", "paper", "scenarios", "synthetic-a.json")
SEED = 20261025
DAYS = 120
START = date(2025, 1, 2)
SYMBOLS = {  # symbol -> (fictional name, starting price in cents, daily drift, daily volatility)
    "SAMPLE-A": ("Sample Company A (fictional)", 5000, 0.0004, 0.018),
    "SAMPLE-B": ("Sample Company B (fictional)", 12000, 0.0001, 0.028),
}


def business_days(start, count):
    days, d = [], start
    while len(days) < count:
        if d.weekday() < 5:
            days.append(d.isoformat())
        d += timedelta(days=1)
    return days


def build(seed=SEED, days=DAYS):
    rng = random.Random(seed)
    bars = {}
    for symbol, (_, start_cents, drift, vol) in SYMBOLS.items():
        series, close = [], start_cents
        for _ in range(days):
            open_ = max(1, round(close * (1 + rng.gauss(0, vol / 4))))
            close = max(1, round(open_ * (1 + rng.gauss(drift, vol))))
            high = max(open_, close) + round(max(open_, close) * abs(rng.gauss(0, vol / 3)))
            low = max(1, min(open_, close) - round(min(open_, close) * abs(rng.gauss(0, vol / 3))))
            series.append({"o": open_, "h": high, "l": low, "c": close, "v": rng.randint(200_000, 1_500_000)})
        bars[symbol] = series
    return {
        "id": "synthetic-a",
        "label": "Synthetic practice market A",
        "kind": "synthetic",
        "notice": "Synthetic example prices generated by a computer program. Not real market data, not live quotes, "
                  "and not any real company.",
        "generator": {"script": "scripts/build_synthetic_scenario.py", "seed": seed,
                      "method": "Daily random walk in integer cents with an opening gap, drift and volatility per symbol."},
        "timeframe": "1D",
        "symbols": {s: {"name": v[0]} for s, v in SYMBOLS.items()},
        "dates": business_days(START, days),
        "bars": bars,
    }


def main():
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        json.dump(build(), f, indent=1)
        f.write("\n")
    print(f"wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
