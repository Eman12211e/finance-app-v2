"""Build data/paper/scenarios/synthetic-a.json and synthetic-b.json: fictional daily OHLCV bars from fixed seeds.
Offline, no data source. The same seed always produces the same file. Prices are integer cents; dates are Monday-Friday business days
(market holidays are not modelled). Tickers and companies are fictional; nothing here is real market data."""
import json
import os
import random
from datetime import date, timedelta

OUT_DIR = os.path.join(os.path.dirname(__file__), "..", "data", "paper", "scenarios")
SEED = 20261025
DAYS = 120
START = date(2025, 1, 2)
SYMBOLS = {  # symbol -> (fictional name, starting price in cents, daily drift, daily volatility)
    "SAMPLE-A": ("Sample Company A (fictional)", 5000, 0.0004, 0.018),
    "SAMPLE-B": ("Sample Company B (fictional)", 12000, 0.0001, 0.028),
}

# synthetic-b: 12 symbols in 6 sectors; daily returns share a sector shock, plus two scripted events.
SEED_B = 20261026
DAYS_B = 250
SECTOR_CORRELATION = 0.6
SYMBOLS_B = {  # symbol -> (fictional name, sector, starting price in cents, daily drift, daily volatility)
    "SYN-TEC1": ("Sample Software Co. (fictional)", "Technology", 14000, 0.0007, 0.024),
    "SYN-TEC2": ("Sample Chip Co. (fictional)", "Technology", 6000, 0.0005, 0.030),
    "SYN-HLT1": ("Sample Pharma Co. (fictional)", "Healthcare", 9500, 0.0003, 0.016),
    "SYN-HLT2": ("Sample Clinic Co. (fictional)", "Healthcare", 3200, 0.0002, 0.020),
    "SYN-ENR1": ("Sample Oil Co. (fictional)", "Energy", 7200, 0.0001, 0.022),
    "SYN-ENR2": ("Sample Solar Co. (fictional)", "Energy", 1800, 0.0004, 0.034),
    "SYN-FIN1": ("Sample Bank Co. (fictional)", "Financials", 5400, 0.0002, 0.015),
    "SYN-FIN2": ("Sample Insurance Co. (fictional)", "Financials", 11000, 0.0002, 0.012),
    "SYN-CON1": ("Sample Grocery Co. (fictional)", "Consumer", 4500, 0.0002, 0.011),
    "SYN-CON2": ("Sample Apparel Co. (fictional)", "Consumer", 2600, 0.0003, 0.021),
    "SYN-IND1": ("Sample Rail Co. (fictional)", "Industrials", 16500, 0.0002, 0.014),
    "SYN-IND2": ("Sample Machinery Co. (fictional)", "Industrials", 8300, 0.0003, 0.019),
}
EARNINGS_GAP = {"day": 90, "symbol": "SYN-TEC2", "gap": 0.14}  # opens 14% above the previous close
DRAWDOWN = {"from_day": 170, "to_day": 189, "daily": -0.009}  # every symbol drifts down ~16% over 20 days


def business_days(start, count):
    days, d = [], start
    while len(days) < count:
        if d.weekday() < 5:
            days.append(d.isoformat())
        d += timedelta(days=1)
    return days


def build(seed=SEED, days=DAYS):
    rng = random.Random(seed)
    bars = {}
    for symbol, (_, start_cents, drift, vol) in SYMBOLS.items():
        series, close = [], start_cents
        for _ in range(days):
            open_ = max(1, round(close * (1 + rng.gauss(0, vol / 4))))
            close = max(1, round(open_ * (1 + rng.gauss(drift, vol))))
            high = max(open_, close) + round(max(open_, close) * abs(rng.gauss(0, vol / 3)))
            low = max(1, min(open_, close) - round(min(open_, close) * abs(rng.gauss(0, vol / 3))))
            series.append({"o": open_, "h": high, "l": low, "c": close, "v": rng.randint(200_000, 1_500_000)})
        bars[symbol] = series
    return {
        "id": "synthetic-a",
        "label": "Synthetic practice market A",
        "kind": "synthetic",
        "notice": "Synthetic example prices generated by a computer program. Not real market data, not live quotes, "
                  "and not any real company.",
        "generator": {"script": "scripts/build_synthetic_scenario.py", "seed": seed,
                      "method": "Daily random walk in integer cents with an opening gap, drift and volatility per symbol."},
        "timeframe": "1D",
        "symbols": {s: {"name": v[0]} for s, v in SYMBOLS.items()},
        "dates": business_days(START, days),
        "bars": bars,
    }


def build_b(seed=SEED_B, days=DAYS_B):
    rng = random.Random(seed)
    sectors = sorted({v[1] for v in SYMBOLS_B.values()})
    bars = {s: [] for s in SYMBOLS_B}
    closes = {s: v[2] for s, v in SYMBOLS_B.items()}
    for day in range(days):
        shock = {sector: rng.gauss(0, 1) for sector in sectors}
        drawdown = DRAWDOWN["daily"] if DRAWDOWN["from_day"] <= day <= DRAWDOWN["to_day"] else 0
        for symbol, (_, sector, _, drift, vol) in SYMBOLS_B.items():
            event = (day, symbol) == (EARNINGS_GAP["day"], EARNINGS_GAP["symbol"])
            open_ = max(1, round(closes[symbol] * (1 + (EARNINGS_GAP["gap"] if event else rng.gauss(0, vol / 4)))))
            move = SECTOR_CORRELATION * shock[sector] + (1 - SECTOR_CORRELATION ** 2) ** 0.5 * rng.gauss(0, 1)
            close = max(1, round(open_ * (1 + drift + drawdown + vol * move)))
            high = max(open_, close) + round(max(open_, close) * abs(rng.gauss(0, vol / 3)))
            low = max(1, min(open_, close) - round(min(open_, close) * abs(rng.gauss(0, vol / 3))))
            volume = rng.randint(200_000, 1_500_000) * (3 if event else 1)
            bars[symbol].append({"o": open_, "h": high, "l": low, "c": close, "v": volume})
            closes[symbol] = close
    dates = business_days(START, days)
    return {
        "id": "synthetic-b",
        "label": "Synthetic practice market B (12 tickers, 6 sectors)",
        "kind": "synthetic",
        "notice": "Synthetic example prices generated by a computer program. Not real market data, not live quotes, "
                  "and not any real company.",
        "generator": {"script": "scripts/build_synthetic_scenario.py", "seed": seed,
                      "method": "Daily random walk in integer cents with an opening gap; each day's move mixes a "
                                f"shared sector shock (correlation {SECTOR_CORRELATION}) with the symbol's own noise."},
        "timeframe": "1D",
        "symbols": {s: {"name": v[0], "sector": v[1]} for s, v in SYMBOLS_B.items()},
        "sectors": sectors,
        "events": [
            {"kind": "earnings_gap", "symbol": EARNINGS_GAP["symbol"], "day": EARNINGS_GAP["day"],
             "date": dates[EARNINGS_GAP["day"]],
             "description": "A scripted fictional earnings surprise: the stock opens well above the previous close."},
            {"kind": "drawdown", "from_day": DRAWDOWN["from_day"], "to_day": DRAWDOWN["to_day"],
             "from_date": dates[DRAWDOWN["from_day"]], "to_date": dates[DRAWDOWN["to_day"]],
             "description": "A scripted market-wide decline: every symbol drifts lower for 20 simulated days."},
        ],
        "dates": dates,
        "bars": bars,
    }


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for market in (build(), build_b()):
        path = os.path.join(OUT_DIR, f"{market['id']}.json")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            json.dump(market, f, indent=1)
            f.write("\n")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
